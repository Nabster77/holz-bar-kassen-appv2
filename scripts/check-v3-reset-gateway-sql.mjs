// WOODMO V3: executes the reset gateway SQL (reset_pos_bookings_v3_authorized)
// in an isolated PGlite database. No real Cloud is touched.
// Checks the service-role guard with the claim formats Supabase/PostgREST
// actually sends, the open-till lock, the grants and that nothing is deleted.
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

const db = new PGlite();
const gateway = readFileSync(
  'supabase/migrations/20261114140000_woodmo_v3_admin_password_reset_gateway.sql', 'utf8');
let passed = 0;
async function check(name, fn) {
  await fn();
  passed++;
  console.log('BESTANDEN: ' + name);
}
const generation = async () =>
  Number((await db.query('SELECT COALESCE(max(id),0)::int g FROM public.pos_booking_resets')).rows[0].g);
const counts = async () => (await db.query(`SELECT
  (SELECT count(*)::int FROM public.pos_transactions) sales,
  (SELECT count(*)::int FROM public.pos_cash_sessions) sessions,
  (SELECT count(*)::int FROM public.pos_stornos) stornos`)).rows[0];

// Each call runs in its own transaction, like one PostgREST request.
async function callAs({ claims, legacyRole }) {
  await db.exec('BEGIN');
  try {
    if (claims !== undefined) {
      await db.query("SELECT set_config('request.jwt.claims', $1, true)", [claims]);
    }
    if (legacyRole !== undefined) {
      await db.query("SELECT set_config('request.jwt.claim.role', $1, true)", [legacyRole]);
    }
    const { rows } = await db.query('SELECT public.reset_pos_bookings_v3_authorized() r');
    await db.exec('COMMIT');
    return rows[0].r;
  } catch (error) {
    await db.exec('ROLLBACK');
    throw error;
  }
}
const rejectsService = (promise) =>
  assert.rejects(promise, /Nur serverseitig autorisierter Dienst/);

try {
  await db.exec(`
    CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
    CREATE TABLE public.pos_booking_resets(
      id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reset_at bigint);
    INSERT INTO public.pos_booking_resets(id, reset_at) VALUES (2, 1794623500000);
    SELECT setval(pg_get_serial_sequence('public.pos_booking_resets','id'), 2, true);
    CREATE TABLE public.pos_transactions(id text PRIMARY KEY, location text,
      booking_generation bigint, timestamp bigint, data jsonb);
    CREATE TABLE public.pos_cash_sessions(id text PRIMARY KEY, location text,
      booking_generation bigint, date text, data jsonb);
    CREATE TABLE public.pos_stornos(id text PRIMARY KEY, booking_generation bigint, data jsonb);
    INSERT INTO public.pos_cash_sessions VALUES ('FN-closed','Friedrichshafen',2,'2026-11-14',
      '{"closed":true,"dailyCloseFinalizedAt":1794659735000,"dailyCloseSnapshot":{"total":67.5}}');
    INSERT INTO public.pos_transactions VALUES ('sale-1','Friedrichshafen',2,1794623600000,
      '{"id":"sale-1","cashSessionId":"FN-closed","total":28}');
    INSERT INTO public.pos_stornos VALUES ('storno-1',2,'{"originalId":"sale-0"}');
  `);
  await db.exec(gateway);
  const before = await counts();

  await check('01 Ohne Rolle (keine Claims) wird abgelehnt', async () => {
    await rejectsService(callAs({}));
    assert.equal(await generation(), 2);
  });
  await check('02 Rolle authenticated (Tablet-Anmeldung) wird abgelehnt', async () => {
    await rejectsService(callAs({ claims: '{"role":"authenticated","email":"admin@kasse.local"}' }));
    assert.equal(await generation(), 2);
  });
  await check('03 Rolle anon wird abgelehnt', async () => {
    await rejectsService(callAs({ claims: '{"role":"anon"}' }));
    assert.equal(await generation(), 2);
  });
  await check('04 Leere Claims werden abgelehnt', async () => {
    await rejectsService(callAs({ claims: '' }));
    assert.equal(await generation(), 2);
  });
  await check('05 service_role in request.jwt.claims (aktuelles Supabase) setzt Reset', async () => {
    const result = await callAs({ claims: '{"role":"service_role"}' });
    assert.equal(Number(result.generation), 3);
    assert.ok(Number.isFinite(Number(result.reset_at)));
    assert.equal(await generation(), 3);
  });
  await check('06 Reset loescht keine Buchungen, Kassen oder Stornos', async () => {
    assert.deepEqual(await counts(), before);
  });
  await check('07 Alte Einzel-Einstellung request.jwt.claim.role funktioniert weiterhin', async () => {
    const result = await callAs({ legacyRole: 'service_role' });
    assert.equal(Number(result.generation), 4);
  });
  await check('08 Offene Kasse sperrt auch den service_role-Reset', async () => {
    await db.query(`INSERT INTO public.pos_cash_sessions VALUES ('BR-open','Bregenz',4,'2026-11-14',
      '{"closed":false,"openingBalance":400}')`);
    await assert.rejects(callAs({ claims: '{"role":"service_role"}' }), /Kasse\(n\) noch offen/);
    assert.equal(await generation(), 4);
  });
  await check('09 Geschlossen ohne endgueltigen Abschluss sperrt ebenfalls', async () => {
    await db.query(`UPDATE public.pos_cash_sessions SET data='{"closed":true}' WHERE id='BR-open'`);
    await assert.rejects(callAs({ claims: '{"role":"service_role"}' }), /Kasse\(n\) noch offen/);
    assert.equal(await generation(), 4);
  });
  await check('10 Ausfuehrungsrecht nur fuer service_role', async () => {
    const { rows } = await db.query(`SELECT
      has_function_privilege('service_role','public.reset_pos_bookings_v3_authorized()','EXECUTE') svc,
      has_function_privilege('authenticated','public.reset_pos_bookings_v3_authorized()','EXECUTE') auth,
      has_function_privilege('anon','public.reset_pos_bookings_v3_authorized()','EXECUTE') anon`);
    assert.deepEqual(rows[0], { svc: true, auth: false, anon: false });
  });

  console.log(`WOODMO V3 RESET-GATEWAY-SQL: ${passed}/10 VERHALTENSTESTS BESTANDEN - NUR ISOLIERTE PGLITE.`);
} finally {
  await db.close();
}
